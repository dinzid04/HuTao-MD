function formatFancyFont(text, fontKey = 'font1') {
    const fontData = FONT_MAPS[fontKey] || FONT_MAPS.font1;
    const converted = String(text || '').split('').map(c => fontData.map[c] || c).join('');
    return converted;
}

function getAllFancyFonts(text) {
    const rawText = String(text || '').trim();
    let resultText = `\`𝗙𝗔𝗡𝗖𝗬 𝗙𝗢𝗡𝗧𝗦 (𝟭 - 𝟭𝟬)\`\n> ᴛᴇᴋs ᴀsʟɪ : ${rawText}\n\n`;
    for (let i = 1; i <= 10; i++) {
        const key = `font${i}`;
        const f = FONT_MAPS[key];
        const converted = formatFancyFont(rawText, key);
        resultText += `> *${i}. ${f.name}* (${key})\n> ${converted}\n\n`;
    }
    resultText += `_ɢᴜɴᴀᴋᴀɴ .font1 <teks> sᴀᴍᴘᴀɪ .font10 <teks> ᴜɴᴛᴜᴋ ᴍᴇɴɢɢᴜɴᴀᴋᴀɴ ғᴏɴᴛ sᴇᴄᴀʀᴀ ʟᴀɴɢsᴜɴɢ._`;
    return resultText.trim();
}

